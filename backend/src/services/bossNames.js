function getBoss(bossId) {
  return BOSSES[Number(bossId)] || { name: `Raid ${bossId}`, level: 999 };
}

function getBossName(bossId) {
  return getBoss(bossId).name;
}

function getBossLevel(bossId) {
  return getBoss(bossId).level;
}

function compareBossLevel(a, b) {
  const levelA = a.level ?? 999;
  const levelB = b.level ?? 999;
  if (levelA !== levelB) {
    return levelA - levelB;
  }
  return String(a.name).localeCompare(String(b.name));
}

module.exports = {
  getBossName,
  getBossLevel,
  compareBossLevel,
};
